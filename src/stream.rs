use std::io;

use futures_core::Stream;
use futures_core::stream::BoxStream;
use futures_util::StreamExt;
use tracing::Span;

/// Represents elements that make up an LLM's streaming response.
///
/// The stream is represented using a flattened stream consisting of many 'inner' streams
/// (or "channels").
#[derive(Debug, Clone)]
pub enum ResponseEvent {
    /// Optional reasoning done by the LLM.
    ///
    /// Reasoning can arrive in chunks.
    Reasoning(String),
    /// The LLM is outputing a text response message.
    Message(MessageEvent),
    /// The LLM is calling a tool.
    Tool(ToolEvent),
}

/// All events related to response messages created by the LLM.
#[derive(Debug, Clone)]
pub enum MessageEvent {
    /// Sent when the LLM has started generating a new message response.
    Start { index: ChannelIndex },
    /// A chunk of text to append to a specific response.
    Chunk { index: ChannelIndex, delta: String },
    /// Indicates a certain response is complete.
    Complete { index: ChannelIndex },
}

/// All events related to tool calls performed by the LLM.
#[derive(Debug, Clone)]
pub enum ToolEvent {
    /// Sent when the LLM starts calling a tool.
    Start {
        index: ChannelIndex,
        tool_call_id: String,
        name: String,
    },
    /// A chunk to append to a specific tool call's arguments.
    Chunk { index: ChannelIndex, delta: String },
    /// Indicates the LLM has finished generating the tool arguments.
    Complete { index: ChannelIndex },
}

/// Unique identifier for a channel (reasoning, response, tool, ...) in a stream.
pub type ChannelIndex = usize;

/// A streaming response generated by an LLM.
pub struct ResponseStream {
    inner: BoxStream<'static, io::Result<ResponseEvent>>,
    span: Span,
}

impl Unpin for ResponseStream {}

impl ResponseStream {
    /// Wraps an existing stream.
    pub fn new<S>(stream: S) -> Self
    where
        S: Stream<Item = io::Result<ResponseEvent>> + Send + 'static,
    {
        Self {
            inner: stream.boxed(),
            span: Span::none(),
        }
    }

    /// Returns the stream with the current span attached.
    pub fn instrumented(mut self) -> Self {
        self.span = Span::current();
        self
    }
}

impl Stream for ResponseStream {
    type Item = io::Result<ResponseEvent>;

    fn poll_next(
        self: std::pin::Pin<&mut Self>,
        cx: &mut std::task::Context<'_>,
    ) -> std::task::Poll<Option<Self::Item>> {
        let this = self.get_mut();

        let _guard = this.span.enter();

        this.inner.poll_next_unpin(cx)
    }
}
